/// Sanitize share name for export fragment filenames.
pub(crate) fn sanitize_name(s: &str) -> String {
    s.chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '-' || c == '_' {
                c
            } else {
                '-'
            }
        })
        .collect()
}

/// Stable Export_Id from share name (FNV-1a + base offset).
pub(crate) fn derive_export_id(name: &str, base: u16) -> u16 {
    let mut h: u32 = 0x811c9dc5;
    for b in name.as_bytes() {
        h = h.wrapping_mul(16777619) ^ (*b as u32);
    }
    base + (h % 55000) as u16
}

/// Basename for a managed export fragment.
/// Matches write_export_fragments numbering.
pub(crate) fn fragment_basename(index: usize, name: &str) -> String {
    format!("{:02}-{}.conf", index + 10, sanitize_name(name))
}



pub fn generate_all(cfg: &NfsKlldapConfig, paths: &GenerationPaths) -> Result<(), ConfigError> {
    fs::create_dir_all(&paths.exports_dir)?;
    write_sssd_conf(cfg, &paths.sssd_conf)?;
    write_krb5_conf(cfg, &paths.krb5_conf)?;
    // Idmapd.conf shares realm/sssd with ganesha DomainName and idhelper.
    write_idmap_conf(cfg, &paths.idmap_conf)?;
    write_nfs_conf(&paths.nfs_conf)?;
    // Write fragments before main conf so %include targets exist at parse.
    write_export_fragments(cfg, &paths.exports_dir)?;
    write_ganesha_main(cfg, &paths.ganesha_conf, &paths.exports_dir)?;
    Ok(())
}

fn write_sssd_conf(cfg: &NfsKlldapConfig, out: &Path) -> Result<(), ConfigError> {
    let realm = cfg.effective_realm();
    let search_base = cfg
        .sssd
        .ldap_search_base
        .clone()
        .filter(|v| !v.trim().is_empty())
        .unwrap_or_else(|| format!("dc={}", realm.to_lowercase().replace('.', ",dc=")));

    let inputs = sssd_resolver_inputs(&cfg.ldap_uri, &cfg.sssd, &realm);
    let mapping = resolve_posix_attribute_mapping(&inputs.posix_mapping);
    let (user_base, group_base) = effective_ldap_search_bases(&inputs.search_bases, &realm);

    let domain_name = cfg
        .sssd
        .domain
        .clone()
        .filter(|v| !v.trim().is_empty())
        .unwrap_or_else(|| "default".to_string());

    let is_plain_ldap = cfg.ldap_uri.starts_with("ldap://");

    let auth_provider = cfg
        .sssd
        .auth_provider
        .clone()
        .filter(|v| !v.trim().is_empty())
        .unwrap_or_else(|| "ldap".to_string());

    let enumerate = cfg.sssd.enumerate.unwrap_or(false);

    // Editing nfs-klldap.conf triggers watcher or SIGHUP regen of sssd.conf.
    let header = format!(
        r#"# GENERATED by nfs-klldap-config — do not edit (source: nfs-klldap.conf).
# Realm: {realm} | domain: {domain} | auth: {auth} | enumerate: {enumerate}

"#,
        realm = realm,
        domain = domain_name,
        auth = auth_provider,
        enumerate = enumerate,
    );

    let mut content = header;
    content.push_str(&format!(
        r#"[sssd]
config_file_version = 2
services = nss, pam
domains = {domain_name}

[nss]
filter_users = root
filter_groups = root

[domain/{domain_name}]
id_provider = ldap
auth_provider = {auth_provider}
ldap_uri = {ldap_uri}
ldap_search_base = {search_base}
ldap_default_bind_dn = {bind_dn}
ldap_default_authtok = {bind_pw}
cache_credentials = true
# SSSD entry cache timeouts from nfs-klldap.conf (defaults below).
entry_cache_timeout = {entry_cache_timeout}
entry_negative_timeout = {entry_negative_timeout}
"#,
        domain_name = domain_name,
        auth_provider = auth_provider,
        ldap_uri = cfg.ldap_uri,
        search_base = search_base,
        bind_dn = cfg.sssd.ldap_default_bind_dn,
        bind_pw = cfg.sssd.ldap_default_authtok,
        entry_cache_timeout = cfg.sssd.entry_cache_timeout.unwrap_or(3600),
        entry_negative_timeout = cfg.sssd.entry_negative_timeout.unwrap_or(60),
    ));

    content.push_str(&build_ldap_domain_options(
        cfg,
        &user_base,
        &group_base,
        is_plain_ldap,
        &mapping,
    ));

    fs::write(out, content.as_bytes())?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(out, fs::Permissions::from_mode(0o600))?;
    }
    Ok(())
}

fn build_ldap_domain_options(
    cfg: &NfsKlldapConfig,
    user_base: &str,
    group_base: &str,
    is_plain_ldap: bool,
    mapping: &PosixAttributeMapping,
) -> String {
    let s = &cfg.sssd;
    let user_attr_list = {
        let mut a = vec![
            mapping.user_name.as_str(),
            mapping.user_uid_number.as_str(),
            mapping.user_gid_number.as_str(),
            mapping.user_home_directory.as_str(),
            mapping.user_shell.as_str(),
            "objectClass",
        ];
        if let Some(f) = s
            .ldap_user_fullname
            .as_ref()
            .filter(|v| !v.trim().is_empty())
        {
            let f = f.trim();
            if !a.iter().any(|x| x.eq_ignore_ascii_case(f)) {
                a.push(f);
            }
        }
        a.join(",")
    };
    let group_attr_list = {
        let a = [
            mapping.group_name.as_str(),
            mapping.group_gid_number.as_str(),
            mapping.group_member.as_str(),
            "objectClass",
        ];
        a.join(",")
    };

    let enumerate = if s.enumerate.unwrap_or(false) {
        "true"
    } else {
        "false"
    };

    let ldap_schema = s
        .ldap_schema
        .as_ref()
        .filter(|v| !v.trim().is_empty())
        .map(|v| v.trim().to_string())
        .unwrap_or_else(|| "rfc2307bis".to_string());

    let auth_provider = s
        .auth_provider
        .as_ref()
        .filter(|v| !v.trim().is_empty())
        .map(|v| v.trim().to_string())
        .unwrap_or_else(|| "ldap".to_string());

    let mut out = format!(
        r#"ldap_user_search_base = {user_base}
ldap_user_search_scope = sub
ldap_user_object_class = {user_obj}
ldap_user_name = {u_name}
ldap_user_uid_number = {u_uid}
ldap_user_gid_number = {u_gid}
ldap_user_home_directory = {u_home}
ldap_user_shell = {u_shell}

ldap_group_search_base = {group_base}
ldap_group_search_scope = sub
ldap_group_object_class = {group_obj}
ldap_group_name = {g_name}
ldap_group_gid_number = {g_gid}
# For KLLDAP + rfc2307bis we recommend "member" (DNs) or "uniqueMember".
# Defaults to "member" when kllldap_ignored_attributes is active.
ldap_group_member = {g_member}

ldap_schema = {ldap_schema}
ldap_pwd_policy = none
ldap_id_mapping = false
enumerate = {enumerate}
access_provider = {access}"#,
        user_base = user_base,
        user_obj = mapping.user_object_class,
        u_name = mapping.user_name,
        u_uid = mapping.user_uid_number,
        u_gid = mapping.user_gid_number,
        u_home = mapping.user_home_directory,
        u_shell = mapping.user_shell,
        group_base = group_base,
        group_obj = mapping.group_object_class,
        g_name = mapping.group_name,
        g_gid = mapping.group_gid_number,
        g_member = mapping.group_member,
        ldap_schema = ldap_schema,
        enumerate = enumerate,
        access = s
            .access_provider
            .as_deref()
            .filter(|v| !v.trim().is_empty())
            .unwrap_or("permit"),
    );


    out.push_str(&format!(
        "\n# Informational (computed from active POSIX attribute mappings above):\n# ldap_user_extra_attrs only *adds* (it does not restrict).\n# Shown for reference/debugging only:\n#ldap_user_attributes = {}\n#ldap_group_attributes = {}",
        user_attr_list, group_attr_list
    ));

    // The krb5 auth is avoid extra LDAP roundtrips.
    if auth_provider == "krb5" {
        out.push_str("\nchpass_provider = krb5");
        // Krb5_validate=false avoids extra LDAP lookups during TGT validation.
        if s.krb5_validate.is_none() {
            out.push_str("\nkrb5_validate = false");
        }
    }

    // Krb5_realm, server, and kpasswd use effective_realm and ldap_uri host.
    let kdc_host = crate::extract_host_from_uri(&cfg.ldap_uri);
    // Caller must have run validate_and_derive before krb5 generation.
    let realm = cfg.effective_realm();

    // The krb5_realm is always the effective realm (same as kerberos.realm.
    out.push_str(&format!("\nkrb5_realm = {}", realm));

    let krb5_server_val = s
        .krb5_server
        .as_ref()
        .filter(|v| !v.trim().is_empty())
        .map(|v| v.trim().to_string())
        .unwrap_or_else(|| kdc_host.clone());

    out.push_str(&format!("\nkrb5_server = {}", krb5_server_val));

    // The kpasswd is auto to same host (common for co-located) unless.
    let krb5_kpasswd_val = s
        .krb5_kpasswd
        .as_ref()
        .filter(|v| !v.trim().is_empty())
        .map(|v| v.trim().to_string())
        .unwrap_or_else(|| kdc_host.clone());
    out.push_str(&format!("\nkrb5_kpasswd = {}", krb5_kpasswd_val));

    // Optional fields — only emit when explicitly set.
    if let Some(v) = &s.ldap_tls_reqcert {
        if !v.trim().is_empty() {
            out.push_str(&format!("\nldap_tls_reqcert = {}", v.trim()));
        }
    }
    if let Some(v) = &s.ldap_tls_cacert {
        if !v.trim().is_empty() {
            out.push_str(&format!("\nldap_tls_cacert = {}", v.trim()));
        }
    }
    if let Some(v) = s.ldap_id_use_start_tls {
        out.push_str(&format!(
            "\nldap_id_use_start_tls = {}",
            if v { "true" } else { "false" }
        ));
    }
    if let Some(v) = s
        .ldap_user_fullname
        .as_ref()
        .filter(|v| !v.trim().is_empty())
    {
        out.push_str(&format!("\nldap_user_fullname = {}", v.trim()));
    }

    // Optional krb5 knobs beyond auto-derived server/kpasswd above.
    if let Some(v) = s.krb5_validate {
        out.push_str(&format!(
            "\nkrb5_validate = {}",
            if v { "true" } else { "false" }
        ));
    }
    if let Some(v) = s.krb5_store_password_if_offline {
        out.push_str(&format!(
            "\nkrb5_store_password_if_offline = {}",
            if v { "true" } else { "false" }
        ));
    }

    // Plain ldap is // safety flag.
    if is_plain_ldap
        && s.ldap_auth_disable_tls_never_use_in_production
            .unwrap_or(true)
    {
        out.push_str("\nldap_auth_disable_tls_never_use_in_production = true");
    }


    let emit_ignores = s.kllldap_ignored_attributes.unwrap_or(true);
    if emit_ignores {
        out.push_str("\n\n");
        out.push_str(&ignored_attributes::get_kllldap_ignored_attributes_comment_block());
    }

    out
}

fn write_krb5_conf(cfg: &NfsKlldapConfig, out: &Path) -> Result<(), ConfigError> { 
    let realm = cfg.effective_realm();
    let kdc_host = crate::extract_host_from_uri(&cfg.ldap_uri);

    let content = format!(
        r#"[libdefaults]
    default_realm = {realm}
    dns_lookup_realm = false
    dns_lookup_kdc = false
    rdns = false
    ticket_lifetime = 24h
    renew_lifetime = 7d
    forwardable = true

[realms]
    {realm} = {{
        kdc = {kdc_host}
        admin_server = {kdc_host}
    }}

[domain_realm]
    .{realm_lower} = {realm}
    {realm_lower} = {realm}
"#,
        realm = realm,
        realm_lower = realm.to_lowercase(),
        kdc_host = kdc_host,
    );

    fs::write(out, content.as_bytes())?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = fs::set_permissions(out, fs::Permissions::from_mode(0o644));
    }
    Ok(())
}

/// Write /etc/nfs.conf with use-machine-creds=0 for krb5p user TGT clients.
fn write_nfs_conf(out: &Path) -> Result<(), ConfigError> {
    let content = r#"# GENERATED by nfs-klldap-config — do not edit (source: nfs-klldap.conf).
[general]
pipefs-directory=/run/rpc_pipefs

[gssd]
use-machine-creds=0
"#;
    fs::write(out, content.as_bytes())?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = fs::set_permissions(out, fs::Permissions::from_mode(0o644));
    }
    Ok(())
}

/// Writes /etc/idmapd.conf with Domain from effective_realm and GSS nsswitch.
fn write_idmap_conf(cfg: &NfsKlldapConfig, out: &Path) -> Result<(), ConfigError> {
    let realm = cfg.nfsv4_domain();

    let content = format!(
        r#"# GENERATED by nfs-klldap-config — do not edit (source: nfs-klldap.conf).
# Routes user@REALM via nsswitch + getpwnam (nss_wrapper/sssd) for krb5*.

[General]
Verbosity = 0
Domain = {realm}
Local-Realms = {realm}

[Mapping]
Nobody-User = {nobody_u}
Nobody-Group = {nobody_g}

[Translation]
Method = {method}
GSS-Methods = {gss}
# krb5/krb5p/krb5i: nsswitch + UseGetpwnam=true (getpwuid_r + getgrouplist LogInfo); see ganesha-ctl id-resolve
"#,
        realm = realm,
        nobody_u = constants::IDMAPD_NOBODY_USER,
        nobody_g = constants::IDMAPD_NOBODY_GROUP,
        method = constants::IDMAPD_TRANSLATION_METHOD,
        gss = constants::IDMAPD_GSS_METHODS,
    );

    fs::write(out, content.as_bytes())?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = fs::set_permissions(out, fs::Permissions::from_mode(0o644));
    }
    Ok(())
}

fn ganesha_debug_enabled() -> bool {
    std::env::var("GANESHA_DEBUG")
        .map(|v| {
            matches!(
                v.trim().to_ascii_lowercase().as_str(),
                "true" | "1" | "yes" | "on"
            )
        })
        .unwrap_or(false)
}

// Ganesha 9.6 pwnam=nsswitch idhelper materializes principals For hybrid.
fn write_ganesha_main(
    cfg: &NfsKlldapConfig,
    out: &Path,
    exports_dir: &Path,
) -> Result<(), ConfigError> {
    let sec = &cfg.ganesha.default_security;
    let realm = cfg.nfsv4_domain();

    // Explicit %include per share for deterministic load order (no glob.
    let includes: String = cfg
        .shares
        .iter()
        .enumerate()
        .map(|(i, s)| {
            let name = fragment_basename(i, &s.name);
            format!("%include {}/{}\n", exports_dir.display(), name)
        })
        .collect();

    let rpc_cred_fallback = cfg
        .ganesha
        .enable_rpc_cred_fallback
        .unwrap_or(true);
    let rpc_cred_line = if rpc_cred_fallback {
        "    enable_rpc_cred_fallback = true;  # RPC token gids when uid2grp fails; may mask incomplete nss_wrapper membership.\n"
    } else {
        "    enable_rpc_cred_fallback = false;  # fail closed on uid2grp miss (idhelper authoritative).\n"
    };
    let idmap_validity = cfg
        .ganesha
        .idmapped_validity_secs
        .unwrap_or(constants::GANESHA_IDMAPPED_VALIDITY_SECS);

    let mut content = format!(
        r#"NFS_CORE_PARAM {{
    Protocols = {proto};
    Enable_UDP = false;
    Bind_addr = 0.0.0.0;
    NFS_Port = 2049;
    Enable_RQUOTA = false;
    Enable_NLM = false;
    Allow_Set_Io_Flusher_Fail = true;
{rpc_cred_line}}}

DIRECTORY_SERVICES {{
    DomainName = {realm};
    Pwnam_Implementation = {pwnam};
    Pwutils_Use_Fully_Qualified_Names = true;  # principal2uid uses user@ form; getgrouplist uses passwd login from getpwuid_r.
    Root_Kerberos_Principal = {root_krb};
    # Idmapped_* negative cache TTL (seconds); lower reduces miss stickiness, increases NSS load.
    Idmapped_User_Time_Validity = {idmap_validity};
    Idmapped_Group_Time_Validity = {idmap_validity};
}}

NFS_KRB5 {{
    PrincipalName = "nfs";
    KeytabPath = "/etc/krb5.keytab";
    Active_krb5 = TRUE;
}}

NFSV4 {{
    Only_Numeric_Owners = true;
    Allow_Numeric_Owners = true;
    UseGetpwnam = true;  # krb5 uid2grp via getpwuid_r + getgrouplist LogInfo under nss_wrapper/idhelper (_MSPAC_SUPPORT stubs allocate_by_principal).
    RecoveryBackend = fs;
    Lease_Lifetime = 60;
    Grace_Period = 45;
}}

EXPORT_DEFAULTS {{
    SecType = {sec};
    Protocols = {proto};
    # Read_Access_Check_Policy omitted (9.6 default `pre`). Limited/noacl shares emit `post` + comment in per-export fragments.
}}
"#,
        realm = realm,
        sec = sec,
        proto = constants::GANESHA_PROTOCOLS,
        pwnam = constants::GANESHA_PWNAM_IMPL,
        root_krb = constants::GANESHA_ROOT_KRB_PRINCIPALS,
        idmap_validity = idmap_validity,
        rpc_cred_line = rpc_cred_line,
    );

    // Baseline LOG helps operators while GANESHA_DEBUG enables FULL_DEBUG.
    if ganesha_debug_enabled() {
        content.push_str(
            r#"LOG {
    Default_Log_Level = DEBUG;
    Components {
        CLIENTID = FULL_DEBUG;
        SESSIONS = FULL_DEBUG;
        IDMAPPER = FULL_DEBUG;
        NFS4 = DEBUG;
        DISPATCH = DEBUG;
        XPRT = DEBUG;
    }
}

"#,
        );
    } else {
        content.push_str(
            r#"LOG {
    Default_Log_Level = INFO;
    Components {
        CLIENTID = EVENT;
        SESSIONS = EVENT;
        IDMAPPER = EVENT;
        XPRT = EVENT;
    }
}

"#,
        );
    }

    content.push_str(&includes);

    fs::write(out, content.as_bytes())?;
    Ok(())
}

/// Posix-only block for limited FS (9.6 valid keys only). 1 sentence.
/// Emits additional directives + comments for manage_gids=false + POSIX-only shares documenting reduction of rpcsec_gss_fetch_managed_groups attempts via idhelper backstop (AC4/D).
fn posix_only_block() -> &'static str {
    "    Disable_ACL = true;\n    Manage_Gids = false;\n    Read_Access_Check_Policy = \"post\";\n    Enable_NLM = false;\n    Enable_RQUOTA = false;\n    # POSIX_ONLY_EXPORT: conservative posix-only export (AUTH_SYS managed gids off only).\n    # krb5p/krb5i still call rpcsec_gss_fetch_managed_groups -> getpwuid_r + getgrouplist via nss_wrapper/idhelper.\n    # See nfs_creds.c:581-584 + uid2grp.c LogInfo markers in V9.6.\n"
}

/// Build Ganesha 9.6 EXPORT ACL lines.
/// Auto-detect comment from probe results. enable_acl semantics: !enable => Disable_ACL.
/// In limited-FS (noacl) case also emit Read_Access_Check_Policy=post + behavioral guard
/// so nfs_access_op does not reject on ACL-style mask (OP_ACCESS NOTSUPP fix).
pub(crate) fn export_fs_directives(share: &crate::Share, caps: &FsCapabilities) -> (String, String, String, String) {
    let eff = compute_effective_flags(share, caps);
    // Limited/noacl: consolidated posix block (Disable_ACL+Manage_Gids=false+post) before SecType.
    let (disable_acl_line, manage_gids_line, read_access_line) = if !eff.enable_acl {
        let block = posix_only_block().to_string();
        (block.clone(), String::new(), String::new())
    } else {
        let manage = if eff.manage_gids {
            "    Manage_Gids = true;\n".to_string()
        } else {
            "    Manage_Gids = false;\n".to_string()
        };
        (String::new(), manage, String::new())
    };
    let auto_comment = if eff.auto_applied {
        let opts = if caps.mount_options.is_empty() {
            String::new()
        } else {
            format!(" ({})", caps.mount_options.join(","))
        };
        // distinct comment block for hardened posix-only on noacl (ZimaOS) as specified
        if !eff.enable_acl {
            format!(
                "# posix-only conservative mode for noacl btrfs (ZimaOS)\n\
                 # Disable_ACL + Manage_Gids=false + Read_Access_Check_Policy=post\n\
                 # POSIX_ONLY_EXPORT: Disable_ACL+Manage_Gids=false+post — posix getattr/access only\n\
                 # Auto-detected: {}{opts} — ACL-dependent NFSv4 ops disabled for compatibility.\n\
                 # See docs/ganesha-architecture.md#acl-and-filesystem-compatibility\n",
                caps.fstype,
                opts = opts
            )
        } else {
            format!(
                "# Auto-detected: {}{opts} — ACL-dependent NFSv4 ops disabled for compatibility.\n\
                 # See docs/ganesha-architecture.md#acl-and-filesystem-compatibility\n",
                caps.fstype,
                opts = opts
            )
        }
    } else {
        String::new()
    };
    (disable_acl_line, manage_gids_line, auto_comment, read_access_line)
}

fn write_export_fragments(cfg: &NfsKlldapConfig, exports_dir: &Path) -> Result<(), ConfigError> {
    // Remove prior managed fragments (we own exports.d/*.conf).
    if exports_dir.exists() {
        for entry in fs::read_dir(exports_dir)? {
            let p = entry?.path();
            if let Some(name) = p.file_name().and_then(|s| s.to_str()) {
                if name.ends_with(".conf") {
                    let _ = fs::remove_file(&p);
                }
            }
        }
    }

    for (i, share) in cfg.shares.iter().enumerate() {
        let export_id = derive_export_id(&share.name, 1000 + (i as u16 * 10));
        let path = cfg.serve_path_for(share);
        let default_pseudo = format!("/{}", share.name);
        // Client pseudo path may differ from the internal serve path.
        let pseudo_raw = share.export_path.as_deref().unwrap_or(&default_pseudo);
        // Defensive absolutize validate_and_derive normally Guarantees.
        let pseudo = if pseudo_raw.starts_with('/') {
            pseudo_raw.to_string()
        } else {
            format!("/{}", pseudo_raw)
        };
        let default_sec = &cfg.ganesha.default_security;
        let sec = share.security.as_deref().unwrap_or(default_sec);
        let access = if share.rw.unwrap_or(true) { "RW" } else { "RO" };
        let squash = share
            .squash
            .as_deref()
            .unwrap_or(constants::GANESHA_DEFAULT_SQUASH);

        // Resolve Pref* from cache_profile or raw pref_* fallback.
        let (pref_r, pref_w) = if let Some(cp) = &share.cache_profile {
            if let Some((r, w)) = crate::resolve_cache_profile(cp) {
                (Some(r), Some(w))
            } else {
                (share.pref_read, share.pref_write)
            }
        } else {
            (share.pref_read, share.pref_write)
        };

        let pref_read_line = pref_r
            .map(|v| format!("    PrefRead = {};\n", v))
            .unwrap_or_default();
        let pref_write_line = pref_w
            .map(|v| format!("    PrefWrite = {};\n", v))
            .unwrap_or_default();

        let caps = probe_fs_capabilities(Path::new(&path)).unwrap_or_else(|_| FsCapabilities {
            fstype: "unknown".into(),
            mount_options: vec![],
            acl_capable: true,
        });
        let (disable_acl_line, manage_gids_line, auto_comment, read_access_line) =
            export_fs_directives(share, &caps);
        // CLIENT block keeps Protocols=4 and skips access check policy.
        let client_block = format!(
            r#"
    CLIENT {{
        Clients = *;
        Access_Type = {access};
        Protocols = {proto};
    }}

"#,
            access = access,
            proto = constants::GANESHA_PROTOCOLS,
        );

        let krb_note = if sec.starts_with("krb5") {
            if manage_gids_line.contains("true") {
                "# krb5* Manage_Gids=true: AUTH_SYS managed gids; krb5 still uses getpwuid_r + getgrouplist via nss_wrapper/idhelper.\n"
            } else {
                "# krb5* Manage_Gids=false: AUTH_SYS only; krb5p/krb5i still requires full supplemental groups in nss_wrapper.\n"
            }
        } else {
            ""
        };
        let block = format!(
            r#"# Generated from nfs-klldap.conf share "{}"
{auto_comment}{krb_note}EXPORT {{
    Export_Id = {};
    Path = {};
    Pseudo = {};
{disable_acl_line}    SecType = {};
    Squash = {};
{manage_gids_line}{read_access_line}{pref_read_line}{pref_write_line}{client_block}    FSAL {{
        Name = VFS;
    }}
}}
"#,
            share.name,
            export_id,
            path,
            pseudo,
            sec,
            squash,
            auto_comment = auto_comment,
            krb_note = krb_note,
            disable_acl_line = disable_acl_line,
            manage_gids_line = manage_gids_line,
            read_access_line = read_access_line,
            pref_read_line = pref_read_line,
            pref_write_line = pref_write_line,
            client_block = client_block
        );

        let filename = fragment_basename(i, &share.name);
        fs::write(exports_dir.join(filename), block.as_bytes())?;
    }

    Ok(())
}

